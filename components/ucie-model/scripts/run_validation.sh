#!/usr/bin/env bash
# Reproducible end-to-end validation for the standalone UCIe link component.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${OUT:-${ROOT_DIR}/build/validation}"
SUMMARY_DIR="${SUMMARY_DIR:-${OUT}}"
export OUT SUMMARY_DIR
mkdir -p "${OUT}"

read -r -a case_runner <<< "${CASE_RUNNER:-python3 ${ROOT_DIR}/../../common/verif/summary.py}"
"${case_runner[@]}" init --directory "${SUMMARY_DIR}" --expected "${SUMMARY_EXPECTED:?Run via make validate}"
status=0
"${case_runner[@]}" run --directory "${SUMMARY_DIR}" --name unit \
  --counts '^UNIT_PASS=([0-9]+) UNIT_FAIL=([0-9]+)$' -- "${ROOT_DIR}/build/ucie_unit_tests" \
  | tee "${OUT}/validation_unit.log" || status=1
"${case_runner[@]}" run --directory "${SUMMARY_DIR}" --name functional \
  --counts '^PASS=([0-9]+) FAIL=([0-9]+)$' -- bash "${ROOT_DIR}/scripts/run_tests.sh" \
  | tee "${OUT}/validation_tests.log" || status=1
bash "${ROOT_DIR}/scripts/run_sweep.sh" | tee "${OUT}/validation_sweep.log" || status=1
"${case_runner[@]}" finish --directory "${SUMMARY_DIR}" --expected "${SUMMARY_EXPECTED}" \
  --names ${VALIDATION_CASES:?Run via make validate} || status=1
[[ ${status} -eq 0 ]] || exit 1

read -r unit_pass unit_fail func_pass func_fail < <("${PYTHON:-python3}" - "${SUMMARY_DIR}/summary.json" <<'PY'
import json,sys
cases={c['name']:c for c in json.load(open(sys.argv[1]))['cases']}
print(cases['unit']['pass_count'],cases['unit']['fail_count'],cases['functional']['pass_count'],cases['functional']['fail_count'])
PY
)

metric() { awk -F, -v k="$2" '$1==k{print $2}' "$1"; }

CLEAN="${OUT}/tests/t1.csv"
NOISY="${OUT}/tests/t4.csv"
BACKPRESSURE="${OUT}/tests/t7.csv"
CDR="${OUT}/tests/t11.csv"
DESKEW="${OUT}/tests/t12.csv"
HIGH_RATE="${OUT}/tests/t13.csv"
REPORT="${OUT}/LINK_VALIDATION_REPORT.md"
SWEEP_ROWS=$(( $(wc -l < "${OUT}/sweep/summary.csv") - 1 ))

cat > "${REPORT}" <<EOF
# UCIe standalone link validation report

Generated by \`make validate\` on $(date -u '+%Y-%m-%d %H:%M:%S UTC').

## Result

- Unit assertions: ${unit_pass} passed, ${unit_fail} failed.
- Integration assertions: ${func_pass} passed, ${func_fail} failed; details in \`validation_tests.log\`.
- Parameter sweep points: ${SWEEP_ROWS}.
- Clean 24 GT/s utilization: $(metric "${CLEAN}" bandwidth_utilization).
- Clean round-trip average/P95/P99 latency: $(metric "${CLEAN}" avg_latency_ns) / $(metric "${CLEAN}" p95_latency_ns) / $(metric "${CLEAN}" p99_latency_ns) ns.
- Clean SER/BER: $(metric "${CLEAN}" symbol_error_rate) / $(metric "${CLEAN}" bit_error_rate).
- Noisy-link SER/BER and replay count: $(metric "${NOISY}" symbol_error_rate) / $(metric "${NOISY}" bit_error_rate) / $(metric "${NOISY}" tx_replay_flits).
- Backpressure events: FDI=$(metric "${BACKPRESSURE}" fdi_backpressure_events), retry-buffer=$(metric "${BACKPRESSURE}" retry_buffer_full_events).
- Forced CDR lock losses: $(metric "${CDR}" cdr_lock_loss_count); final state=$(metric "${CDR}" link_state).
- Deskew failures: $(metric "${DESKEW}" deskew_failures); all delivered=$(metric "${DESKEW}" delivered_flits).
- 48 GT/s capacity/utilization: $(metric "${HIGH_RATE}" capacity_gbps) Gbps / $(metric "${HIGH_RATE}" bandwidth_utilization).

## Reproduction

Run from the project root:

\`\`\`bash
make validate
\`\`\`

Raw functional metrics are under \`tests/\` beside this report; the rate/lane/noise/jitter/seed matrix is in \`sweep/summary.csv\`.
EOF

echo "Validation report written to ${REPORT}"
